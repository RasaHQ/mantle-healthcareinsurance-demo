"""Write the "Eval status" section of README.md from the newest eval results.

Inputs:
- e2e: eval/results/e2e/e2e_results_passed.yml and e2e_results_failed.yml, written by
  `rasa test e2e tests/e2e -o eval/results/e2e/e2e_results.yml` (`make e2e`).
- Scenarios: the newest eval/results/<stamp>/summary.json (`make eval`), or the stamp given with --stamp.
- Scripted checks: eval/results/checks/*.json, written by eval/check_consent.py and eval/check_invented_figures.py.

    python -m eval.status [--stamp <results folder>] [--dry-run]

The section sits between the markers `<!-- eval-status:start -->` and `<!-- eval-status:end -->`.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
RESULTS = REPO_ROOT / "eval" / "results"
README = REPO_ROOT / "README.md"
START, END = "<!-- eval-status:start -->", "<!-- eval-status:end -->"
_ID = re.compile(r"^\[([^\]]+)\]\s*(.*)$")


def _e2e() -> tuple[list[str], list[tuple[str, str, str]], str | None]:
    """(passed names, [(failed name, file and line, failed assertion)], date of the results)."""
    passed_file = RESULTS / "e2e" / "e2e_results_passed.yml"
    failed_file = RESULTS / "e2e" / "e2e_results_failed.yml"
    if not passed_file.exists() and not failed_file.exists():
        return [], [], None

    def names(path: Path) -> list[dict]:
        if not path.exists():
            return []
        data = yaml.safe_load(path.read_text()) or {}
        return data.get("test_results") or []

    def name_of(result: dict) -> str:
        return str(result.get("name") or result.get("test_case") or "?")

    def file_of(result: dict) -> str:
        return Path(str(result.get("error_path") or "")).name

    def failure_of(result: dict) -> str:
        failure = result.get("assertion_failure") or {}
        if isinstance(failure, dict):
            assertion = failure.get("assertion") or {}
            if isinstance(assertion, dict):
                kind = assertion.get("type") or ""
                detail = assertion.get("utter_name") or assertion.get("text_matches") or assertion.get("name") or ""
                return f"{kind} {detail}".strip()[:80].replace("|", "/")
            return str(assertion)[:80].replace("|", "/")
        return str(failure)[:80].replace("|", "/")

    date = dt.datetime.fromtimestamp(max(p.stat().st_mtime for p in (passed_file, failed_file) if p.exists()))
    return ([name_of(r) for r in names(passed_file)],
            [(name_of(r), file_of(r), failure_of(r)) for r in names(failed_file)],
            date.strftime("%Y-%m-%d %H:%M"))


def _scenario_areas() -> dict[str, str]:
    """Scenario name -> area folder."""
    areas = {}
    for path in (REPO_ROOT / "eval" / "scenarios").glob("*/*.yml"):
        data = yaml.safe_load(path.read_text()) or {}
        name = (data.get("scenario") or {}).get("name")
        if name:
            areas[name] = path.parent.name
    return areas


def _suite(stamp: str | None) -> tuple[list[dict], str | None]:
    if stamp:
        summary = RESULTS / stamp / "summary.json"
    else:
        candidates = sorted(RESULTS.glob("*/summary.json"), key=lambda p: p.stat().st_mtime)
        summary = candidates[-1] if candidates else None
    if summary is None or not summary.exists():
        return [], None
    return json.loads(summary.read_text()).get("entries") or [], summary.parent.name


def _checks() -> list[dict]:
    return [json.loads(p.read_text()) for p in sorted((RESULTS / "checks").glob("*.json"))]


def _model() -> str:
    text = (REPO_ROOT / "integrations.yml").read_text()
    match = re.search(r"^\s+model:\s*(\S+)", text, re.M)
    return match.group(1) if match else "unknown"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    widths = [max(len(str(r[i])) for r in [header, *rows]) for i in range(len(header))]
    line = lambda r: "| " + " | ".join(str(c).ljust(widths[i]) for i, c in enumerate(r)) + " |"
    return [line(header), "|" + "|".join("-" * (w + 2) for w in widths) + "|", *[line(r) for r in rows]]


def build(stamp: str | None) -> str:
    e2e_passed, e2e_failed, e2e_date = _e2e()
    entries, suite_stamp = _suite(stamp)
    areas = _scenario_areas()
    checks = _checks()
    out = [START, "", "## Eval status", ""]
    out.append(f"Generated by `make eval-status` on {dt.datetime.now():%Y-%m-%d %H:%M}, for the model `{_model()}`. "
               "Failing evals are expected: they mark the paths that the assistant does not handle yet.")
    out.append("")

    full = [e for e in entries if e["runs_passed"] == e["runs_total"]]
    some = [e for e in entries if 0 < e["runs_passed"] < e["runs_total"]]
    none = [e for e in entries if e["runs_passed"] == 0]
    runs = entries[0]["runs_total"] if entries else 0
    rows = []
    if e2e_date:
        total = len(e2e_passed) + len(e2e_failed)
        rows.append(["e2e tests (`make e2e`)", f"{len(e2e_passed)} of {total} passed", e2e_date])
    if entries:
        rows.append([f"Scenarios, {runs} runs each (`make eval`)",
                     f"{len(full)} of {len(entries)} pass every run; {len(some)} pass some runs; {len(none)} pass no run",
                     suite_stamp])
    sweep = RESULTS / (suite_stamp or "-") / "grounding" / "sweep.json"
    if sweep.exists():
        messages = json.loads(sweep.read_text())
        classes: dict[str, int] = defaultdict(int)
        for m in messages:
            for item in m.get("unsupported") or []:
                classes[item.get("class", "other")] += 1
        flagged = sum(1 for m in messages if m.get("unsupported"))
        detail = ", ".join(f"{k} {v}" for k, v in sorted(classes.items()))
        rows.append(["Grounding judge (after `make eval`)", f"{flagged} of {len(messages)} model-written messages flagged ({detail})",
                     f"{suite_stamp}/grounding/REPORT.md"])
    for check in checks:
        rows.append([f"`eval/{check['check']}.py`", f"{check['passed']} of {check['runs']} runs as expected", check["date"].replace("T", " ")])
    out += _table(["Eval", "Result", "Run"], rows) + [""]

    # Per area.
    per_area: dict[str, list[int]] = defaultdict(lambda: [0, 0, 0, 0])
    for name in e2e_passed:
        per_area[_area_of_e2e(name)][0] += 1
    for name, _, _ in e2e_failed:
        per_area[_area_of_e2e(name)][1] += 1
    for e in entries:
        a = _area_of_e2e(e["scenario_name"])
        per_area[a][2] += e["runs_passed"] == e["runs_total"]
        per_area[a][3] += e["runs_passed"] != e["runs_total"]
    out += ["### Per area", "", "The area is the first part of the path id, for example `drug` in `drug.step_therapy`.", ""]
    out += _table(["Area", "e2e passed", "e2e failed", "Scenarios 3/3", "Scenarios below 3/3"],
                  [[a, *map(str, v)] for a, v in sorted(per_area.items())]) + [""]

    if e2e_failed:
        out += [f"### Failing e2e tests ({len(e2e_failed)})", ""]
        out += _table(["Path", "Test", "File", "Failed assertion"],
                      [[*_split(n), f, a] for n, f, a in sorted(e2e_failed)]) + [""]
    if some or none:
        out += [f"### Scenarios below {runs}/{runs} ({len(some) + len(none)})", ""]
        rows = [[*_split(e["scenario_name"]), areas.get(e["scenario_name"], "?"), f"{e['runs_passed']}/{e['runs_total']}"]
                for e in sorted(some + none, key=lambda e: (e["runs_passed"], e["scenario_name"]))]
        out += _table(["Path", "Scenario", "Area", "Runs passed"], rows) + [""]
    for check in checks:
        if check["failed"]:
            counts: dict[str, int] = defaultdict(int)
            for f in check["failed"]:
                counts[f] += 1
            out += [f"### `{check['check']}`: failing cases", ""] + [f"- {f} ({n} failed runs)" for f, n in counts.items()] + [""]
    if entries:
        out += ["<details><summary>All scenarios</summary>", ""]
        rows = [[*_split(e["scenario_name"]), areas.get(e["scenario_name"], "?"), f"{e['runs_passed']}/{e['runs_total']}"]
                for e in sorted(entries, key=lambda e: (areas.get(e["scenario_name"], "?"), e["scenario_name"]))]
        out += _table(["Path", "Scenario", "Area", "Runs passed"], rows) + ["", "</details>", ""]
    out.append(END)
    return "\n".join(out)


def _split(name: str) -> list[str]:
    match = _ID.match(name)
    return [f"`{match.group(1)}`", match.group(2)] if match else ["", name]


def _area_of_e2e(name: str) -> str:
    match = _ID.match(name)
    return match.group(1).split(".")[0] if match else "?"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--stamp", default=None, help="the eval/results folder of the suite run; default: the newest")
    parser.add_argument("--dry-run", action="store_true", help="print the section, do not write README.md")
    args = parser.parse_args()
    section = build(args.stamp)
    if args.dry_run:
        print(section)
        return 0
    text = README.read_text()
    if START in text and END in text:
        text = text[: text.index(START)] + section + text[text.index(END) + len(END):]
    else:
        anchor = "## Swap in your own model"
        text = text.replace(anchor, section + "\n\n" + anchor, 1) if anchor in text else text + "\n" + section + "\n"
    README.write_text(text)
    print(f"README.md: eval status updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
